/** WordPress reports `fr_FR`; `Intl.DisplayNames` wants a BCP-47 `fr-FR`. */
function displayLocale(): string {
  const wpLocale = window.kelunecrm?.locale || 'en_US';
  const [language, region] = wpLocale.split('_');

  return region ? `${language}-${region}` : language;
}

// Constructing Intl is the costly part, not the lookup — build once.
let regionNames: Intl.DisplayNames | null | undefined;
let collator: Intl.Collator | undefined;
let options: Array<{ value: string; label: string }> | undefined;

function names(): Intl.DisplayNames | null {
  if (regionNames === undefined) {
    try {
      regionNames = new Intl.DisplayNames([displayLocale()], {
        type: 'region',
      });
    } catch {
      regionNames = null;
    }
  }

  return regionNames;
}

export function countryName(code: string): string {
  try {
    return names()?.of(code) ?? code;
  } catch {
    return code;
  }
}

export function countryOptions(): Array<{ value: string; label: string }> {
  if (!collator) {
    try {
      collator = new Intl.Collator(displayLocale());
    } catch {
      collator = new Intl.Collator();
    }
  }

  const compare = collator;

  options ??= COUNTRY_CODES.map((code) => ({
    value: code,
    label: countryName(code),
  })).sort((a, b) => compare.compare(a.label, b.label));

  return options;
}
